"""Manim export: turn the live stack into a rendered MP4.

The live viewport is a real-time OpenGL renderer; Manim cannot drive an
interactive camera. Export bridges the two: the current stack is written as a
Manim scene that replays the exact same matrix paths (``matview.core``)
against a styled grid, basis vectors, unit cell and user vectors.
"""

from __future__ import annotations

import pprint
import sys
from datetime import datetime
from pathlib import Path

import numpy as np
from PySide6.QtCore import QObject, QProcess, Signal

from . import core

ROOT = Path(__file__).resolve().parent.parent

SCENE_TEMPLATE = r'''"""Generated by matview -- do not edit by hand."""
from __future__ import annotations

import sys

sys.path.insert(0, __ROOT__)

import numpy as np
from manim import *
from matview.core import MatrixPath

DATA = __DATA__

BG = DATA["background"]
GRID = DATA["grid"]
AXIS = DATA["axis"]
UNIT = DATA["unit"]
BASIS = DATA["basis"]
DIM = DATA["dim"]
EXT = DATA["extent"]
DUR = DATA["duration"]
MATRICES = [np.array(matrix, dtype=float) for matrix in DATA["matrices"]]
VECTORS = DATA["vectors"]
SHOW = DATA["show"]


class MatrixJourney(ThreeDScene if DIM == 3 else Scene):
    def construct(self):
        self.camera.background_color = BG
        if DIM == 3:
            self.set_camera_orientation(phi=66 * DEGREES, theta=-52 * DEGREES, zoom=1.55)

        roots = []
        if SHOW["grid"]:
            if DIM == 2:
                roots.append(
                    NumberPlane(
                        x_range=[-EXT, EXT, 1],
                        y_range=[-EXT, EXT, 1],
                        background_line_style={
                            "stroke_color": GRID,
                            "stroke_width": 1.0,
                            "stroke_opacity": 0.9,
                        },
                        axis_config={
                            "stroke_color": AXIS,
                            "stroke_width": 2.0,
                            "stroke_opacity": 0.65,
                            "include_ticks": False,
                            "include_numbers": False,
                        },
                    )
                )
            else:
                grid = VGroup()
                for i in range(-EXT, EXT + 1):
                    grid.add(Line([i, -EXT, 0], [i, EXT, 0], stroke_color=GRID,
                                  stroke_width=1.0, stroke_opacity=0.85))
                    grid.add(Line([-EXT, i, 0], [EXT, i, 0], stroke_color=GRID,
                                  stroke_width=1.0, stroke_opacity=0.85))
                for direction in (RIGHT, UP, OUT):
                    grid.add(Line(-EXT * direction, EXT * direction, stroke_color=AXIS,
                                  stroke_width=2.0, stroke_opacity=0.65))
                roots.append(grid)

        if SHOW["unit"]:
            if DIM == 2:
                roots.append(
                    Polygon(ORIGIN, RIGHT, UR, UP, stroke_color=UNIT, stroke_width=2.0,
                            stroke_opacity=0.9, fill_color=UNIT, fill_opacity=0.08)
                )
            else:
                corners = [np.array([x, y, z]) for x in (0.0, 1.0)
                           for y in (0.0, 1.0) for z in (0.0, 1.0)]
                cube = VGroup()
                for i, a in enumerate(corners):
                    for b in corners[i + 1:]:
                        if np.sum(np.abs(a - b) > 1e-9) == 1:
                            cube.add(Line(a, b, stroke_color=UNIT, stroke_width=1.6,
                                          stroke_opacity=0.55))
                roots.append(cube)

        labels = []
        if SHOW["basis"]:
            for index in range(DIM):
                direction = [RIGHT, UP, OUT][index]
                color = BASIS[index]
                if DIM == 2:
                    arrow = Vector(direction, color=color, stroke_width=6, tip_length=0.18)
                    labels.append((Text("ijk"[index], color=color, font_size=28), arrow))
                else:
                    arrow = Arrow3D(ORIGIN, direction, color=color, thickness=0.018,
                                    height=0.26, base_radius=0.07)
                roots.append(arrow)

        for item in VECTORS:
            direction = np.array(item["coords"], dtype=float)
            if np.linalg.norm(direction) < 1e-6:
                continue
            if DIM == 2:
                arrow = Vector(direction, color=item["color"], stroke_width=5, tip_length=0.16)
                labels.append((Text(item["label"], color=item["color"], font_size=26), arrow))
            else:
                arrow = Arrow3D(ORIGIN, direction, color=item["color"], thickness=0.016,
                                height=0.24, base_radius=0.065)
            roots.append(arrow)

        self.add(*roots)
        for text, arrow in labels:
            text.add_updater(
                lambda m, a=arrow: m.move_to(a.get_end() + 0.2 * RIGHT + 0.2 * UP)
            )
            self.add(text)

        leaves = []
        seen = set()
        for root in roots:
            for leaf in root.get_family():
                if id(leaf) in seen:
                    continue
                seen.add(id(leaf))
                leaves.append(leaf)

        tracker = ValueTracker(0.0)
        self.add(tracker)
        for matrix in MATRICES:
            path = MatrixPath(matrix)
            for leaf in leaves:
                original = leaf.points.copy()

                def update(mobject, original=original, path=path):
                    current = path.at(tracker.get_value())
                    points = original.copy()
                    points[:, :DIM] = original[:, :DIM] @ current.T
                    mobject.points = points

                leaf.add_updater(update)
            self.play(tracker.animate.set_value(1.0), run_time=DUR, rate_func=smooth)
            for leaf in leaves:
                leaf.clear_updaters()
            tracker.set_value(0.0)
            self.wait(0.3)
        self.wait(0.8)
'''


def build_payload(viewport) -> dict | None:
    dim = viewport.dim
    matrices = [np.asarray(matrix, dtype=float).tolist() for matrix in viewport.stack]
    if not matrices:
        editor = np.asarray(viewport.editor, dtype=float)
        if np.allclose(editor, np.eye(dim), atol=1e-9):
            return None
        matrices = [editor.tolist()]

    vectors = []
    for spec in viewport.vectors:
        coords = np.zeros(3)
        coords[:dim] = np.asarray(spec.coords, dtype=float)[:dim]
        vectors.append(
            {"label": spec.label or "v", "coords": coords.tolist(), "color": spec.color}
        )

    return {
        "dim": dim,
        "matrices": matrices,
        "vectors": vectors,
        "duration": max(0.6, min(2.5, float(viewport.duration))),
        "extent": 8 if dim == 2 else 6,
        "background": "#090C11",
        "grid": "#1D2C3C",
        "axis": "#7B8FA6",
        "unit": "#58C4DD",
        "basis": list(core.BASIS_COLORS),
        "show": {
            "grid": bool(viewport.flags.get("grid", True)),
            "unit": bool(viewport.flags.get("unit", True)),
            "basis": bool(viewport.flags.get("basis", True)),
        },
    }


def build_scene_source(payload: dict) -> str:
    data = pprint.pformat(payload, width=100, sort_dicts=False)
    return SCENE_TEMPLATE.replace("__ROOT__", repr(str(ROOT))).replace("__DATA__", data)


class ManimExporter(QObject):
    logLine = Signal(str)
    finished = Signal(bool, str)

    def __init__(self, parent=None):
        super().__init__(parent)
        self._process = QProcess(self)
        self._process.setProcessChannelMode(QProcess.MergedChannels)
        self._process.readyReadStandardOutput.connect(self._read)
        self._process.finished.connect(self._on_finished)
        self._process.errorOccurred.connect(self._on_error)
        self._stem: str | None = None
        self._media: Path | None = None
        self._cancelled = False

    def busy(self) -> bool:
        return self._process.state() != QProcess.NotRunning

    def render(self, payload: dict, quality: str = "m") -> None:
        if self.busy():
            return
        exports = ROOT / "exports"
        exports.mkdir(exist_ok=True)
        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        stem = f"matrix_{stamp}"
        script = exports / f"{stem}.py"
        script.write_text(build_scene_source(payload), encoding="utf-8")
        self._stem = stem
        self._media = exports / "media"
        self._cancelled = False
        arguments = [
            "-m",
            "manim",
            "render",
            f"-q{quality}",
            "--disable_caching",
            "--media_dir",
            str(self._media),
            "-o",
            stem,
            str(script),
            "MatrixJourney",
        ]
        self._process.setWorkingDirectory(str(ROOT))
        self._process.start(sys.executable, arguments)

    def cancel(self) -> None:
        self._cancelled = True
        if self.busy():
            self._process.kill()

    def _read(self) -> None:
        raw = bytes(self._process.readAllStandardOutput()).decode("utf-8", "replace")
        for line in raw.splitlines():
            if line.strip():
                self.logLine.emit(line)

    def _on_error(self, error) -> None:
        if self._process.state() == QProcess.NotRunning and not self._cancelled:
            self.finished.emit(False, f"could not start manim ({error})")

    def _on_finished(self, code: int, status) -> None:
        if self._cancelled:
            self.finished.emit(False, "render cancelled")
            return
        if code != 0:
            self.finished.emit(False, f"manim exited with code {code}")
            return
        assert self._stem is not None and self._media is not None
        matches = sorted(
            self._media.rglob(f"{self._stem}.mp4"),
            key=lambda path: path.stat().st_mtime,
            reverse=True,
        )
        if matches:
            self.finished.emit(True, str(matches[0]))
        else:
            self.finished.emit(False, "manim finished but no MP4 was found")
